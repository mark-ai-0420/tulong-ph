export const supportedLanguages = [
  { id: 'taglish', label: 'Tagalog / Taglish', shortLabel: 'FIL', region: 'Pambansa / Luzon' },
  { id: 'cebuano', label: 'Cebuano / Bisaya', shortLabel: 'CEB', region: 'Visayas at Mindanao' },
  { id: 'ilocano', label: 'Ilokano / Ilocano', shortLabel: 'ILO', region: 'Hilagang Luzon' },
  { id: 'en', label: 'English', shortLabel: 'EN', region: 'Official / Global' },
] as const satisfies readonly { id: Language; label: string; shortLabel: string; region: string }[];

export function isLanguage(value: unknown): value is Language {
  return typeof value === 'string' && supportedLanguages.some(({ id }) => id === value);
}

export function getNextLanguage(current: Language): Language {
  const index = supportedLanguages.findIndex(({ id }) => id === current);
  return supportedLanguages[(index + 1) % supportedLanguages.length]?.id ?? 'taglish';
}
